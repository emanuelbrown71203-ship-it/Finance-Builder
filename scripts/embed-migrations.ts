/**
 * Bundles the SQL in ./drizzle into a TypeScript module so the in-memory demo
 * database can create its tables without reading files at runtime.
 * Run through `npm run db:generate`.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "drizzle");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const statements = files.flatMap((f) =>
  readFileSync(join(dir, f), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
);

const out = `// Generated by scripts/embed-migrations.ts from ./drizzle. Do not edit.
export const MIGRATION_STATEMENTS: string[] = ${JSON.stringify(statements, null, 2)};
`;

writeFileSync(join(process.cwd(), "src/db/embedded-migrations.ts"), out);
console.log(`Embedded ${statements.length} statements from ${files.length} migration file(s).`);
