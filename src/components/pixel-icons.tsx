export type PixelName = keyof typeof ART;

/** Turns the rows into one path: each run of lit pixels in a row is one rectangle. */
function toPath(rows: readonly string[]): string {
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      const start = x;
      while (x < row.length && row[x] === "#") x++;
      d += `M${start} ${y}h${x - start}v1H${start}z`;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(Object.entries(ART).map(([name, rows]) => [name, toPath(rows)])) as Record<PixelName, string>;

export const isPixelName = (name: string): name is PixelName => name in ART;

export function PixelIcon({ name, size = 20, className }: { name: PixelName; size?: number; className?: string }) {
  return (
    <svg viewBox="0 0 10 10" width={size} height={size} shapeRendering="crispEdges" fill="currentColor" aria-hidden className={className}>
      <path d={PATHS[name]} />
    </svg>
  );
}
